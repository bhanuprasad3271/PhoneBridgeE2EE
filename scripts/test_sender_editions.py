"""Run against a disposable Android emulator; never use on a personal phone."""
import subprocess
import time

PACKAGE = "com.phonebridge.collector"
TEST = "com.phonebridge.collector.EditionSwitchTest"


def adb(*args):
    result = subprocess.run(["adb", *args], text=True, capture_output=True, check=True)
    print(result.stdout)
    return result.stdout


def test(method):
    output = adb("shell", "am", "instrument", "-w", "-r", "-e", "class",
                 f"{TEST}#{method}", f"{PACKAGE}.test/androidx.test.runner.AndroidJUnitRunner")
    assert "OK (1 test)" in output, output
    assert "FAILURES" not in output and "INSTRUMENTATION_FAILED" not in output, output


def install(edition):
    adb("install", "-r", f"collector/build/outputs/apk/{edition}/debug/collector-{edition}-debug.apk")
    adb("install", "-r", f"collector/build/outputs/apk/androidTest/{edition}/debug/collector-{edition}-debug-androidTest.apk")


def start_and_verify(edition):
    adb("shell", "am", "start", "-W", "-n", f"{PACKAGE}/.MainActivity")
    time.sleep(3)
    assert adb("shell", "pidof", PACKAGE).strip(), "Sender crashed on startup"
    adb("shell", "uiautomator", "dump", "/sdcard/edition-ui.xml")
    ui = adb("shell", "cat", "/sdcard/edition-ui.xml")
    if edition == "lite":
        assert "Sender Lite" in ui
        assert "btnLocationSharing" not in ui
    else:
        assert "btnLocationSharing" in ui
    adb("shell", "am", "force-stop", PACKAGE)


if __name__ == "__main__":
    # No production pairing requests or data are generated by this test.
    adb("shell", "svc", "wifi", "disable")
    adb("shell", "svc", "data", "disable")
    install("full")
    test("seedPairing")
    test("verifyPairingAndEdition")
    start_and_verify("full")
    for edition in ("lite", "full", "lite"):
        install(edition)
        test("verifyPairingAndEdition")
        start_and_verify(edition)
    adb("install", "-r", "receiver/build/outputs/apk/debug/receiver-debug.apk")
    adb("shell", "am", "start", "-W", "-n", "com.phonebridge.receiver/.MainActivity")
    time.sleep(3)
    assert adb("shell", "pidof", "com.phonebridge.receiver").strip()
    print("PASS: Full -> Lite -> Full -> Lite; pairing, identity, encrypted data, and UI preserved")
